// Bundles src/lib/profile/refresh/entry.ts (and the real heatmap renderer it imports)
// into one dependency-free ES module, stored as a string the Profile Builder exports.
// Run `npm run gen:refresh-script` after changing the heatmap renderer; the unit tests
// fail if the committed copy is stale.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const OUTPUT = fileURLToPath(new URL("../src/lib/profile/generated/refresh-script.ts", import.meta.url));

export async function bundleRefreshScript() {
  const result = await build({
    entryPoints: [fileURLToPath(new URL("../src/lib/profile/refresh/entry.ts", import.meta.url))],
    bundle: true,
    write: false,
    platform: "node",
    format: "esm",
    target: "node20",
    legalComments: "none",
    charset: "utf8",
  });
  const code = result.outputFiles[0].text;
  return `// Generated by \`npm run gen:refresh-script\` from src/lib/profile/refresh/entry.ts. Do not edit.\nexport const REFRESH_SCRIPT_SOURCE = ${JSON.stringify(code)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, await bundleRefreshScript());
  console.log(`Wrote ${OUTPUT}`);
}
